package app.floatdeck.spatial

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.ImageDecoder
import android.net.Uri
import java.io.File
import java.util.UUID

object SpatialAssets {
    fun prefs(context: Context) = context.getSharedPreferences("spatial", Context.MODE_PRIVATE)

    fun decode(file: File): Bitmap = requireNotNull(BitmapFactory.decodeFile(file.path, BitmapFactory.Options().apply { inMutable = true })) { "无法读取图片" }

    fun import(context: Context, uri: Uri, key: String): File {
        val bitmap = if (android.os.Build.VERSION.SDK_INT >= 28) ImageDecoder.decodeBitmap(ImageDecoder.createSource(context.contentResolver, uri)) { decoder, info, _ ->
            require(info.size.width > 0 && info.size.height > 0)
            val scale = minOf(1.0, 2048.0 / maxOf(info.size.width, info.size.height))
            decoder.setTargetSize(maxOf(1, (info.size.width * scale).toInt()), maxOf(1, (info.size.height * scale).toInt()))
            decoder.allocator = ImageDecoder.ALLOCATOR_SOFTWARE
        }
        else {
            val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
            context.contentResolver.openInputStream(uri).use { BitmapFactory.decodeStream(it, null, bounds) }
            require(bounds.outWidth > 0 && bounds.outHeight > 0) { "无效图片" }
            val options = BitmapFactory.Options()
            while (maxOf(bounds.outWidth, bounds.outHeight) / options.inSampleSize.coerceAtLeast(1) > 2048) {
                options.inSampleSize = options.inSampleSize.coerceAtLeast(1) * 2
            }
            context.contentResolver.openInputStream(uri).use { requireNotNull(BitmapFactory.decodeStream(it, null, options)) }
        }
        try {
            if (key != "image") {
                val image = prefs(context).getString("image", null)?.let(::File)
                require(image != null) { "请先导入原图" }
                val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
                BitmapFactory.decodeFile(image.path, bounds)
                require(kotlin.math.abs(bitmap.width.toFloat() / bitmap.height - bounds.outWidth.toFloat() / bounds.outHeight) < 0.015f) { "深度图/遮罩必须与原图比例一致并逐像素对齐" }
            }
            val file = File(context.filesDir, "spatial-${UUID.randomUUID()}.png")
            file.outputStream().use { check(bitmap.compress(Bitmap.CompressFormat.PNG, 100, it)) }
            if (key == "image") {
                val extension = when (context.contentResolver.getType(uri)) {
                    "image/jpeg" -> "jpg"
                    "image/webp" -> "webp"
                    else -> "png"
                }
                val original = File(context.filesDir, "original-${UUID.randomUUID()}.$extension")
                try {
                    context.contentResolver.openInputStream(uri).use { input ->
                        requireNotNull(input)
                        original.outputStream().use { output ->
                            val bytes = ByteArray(65536)
                            var total = 0L
                            while (true) {
                                val count = input.read(bytes)
                                if (count < 0) break
                                total += count
                                require(total <= 128L * 1024 * 1024) { "原文件超过 128 MiB 限制" }
                                output.write(bytes, 0, count)
                            }
                        }
                    }
                    prefs(context).edit().putString("original", original.path).apply()
                } catch (error: Exception) { original.delete(); file.delete(); throw error }
            }
            prefs(context).edit().putString(key, file.path).apply()
            // Replacing the source invalidates registration of old auxiliary maps.
            if (key == "image") prefs(context).edit().remove("depth").remove("mask").apply()
            return file
        } finally {
            bitmap.recycle()
        }
    }

    /** Original geometric landscape generated by this application; no external art. */
    fun demo(context: Context) {
        val image = Bitmap.createBitmap(1080, 1920, Bitmap.Config.ARGB_8888)
        val depth = Bitmap.createBitmap(1080, 1920, Bitmap.Config.ARGB_8888)
        val c = Canvas(image)
        val d = Canvas(depth)
        val p = Paint(Paint.ANTI_ALIAS_FLAG)
        c.drawColor(Color.rgb(75, 130, 170))
        d.drawColor(Color.rgb(25, 25, 25))
        p.color = Color.rgb(240, 204, 120)
        c.drawCircle(800f, 370f, 140f, p)
        p.color = Color.rgb(25, 25, 25)
        d.drawCircle(800f, 370f, 140f, p)
        p.color = Color.rgb(58, 100, 110)
        c.drawOval(-300f, 850f, 1500f, 2600f, p)
        p.color = Color.rgb(125, 125, 125)
        d.drawOval(-300f, 850f, 1500f, 2600f, p)
        p.color = Color.rgb(30, 62, 60)
        c.drawOval(180f, 580f, 530f, 1450f, p)
        c.drawRect(320f, 1200f, 380f, 1920f, p)
        p.color = Color.rgb(240, 240, 240)
        d.drawOval(180f, 580f, 530f, 1450f, p)
        d.drawRect(320f, 1200f, 380f, 1920f, p)
        for ((key, bitmap) in listOf("image" to image, "depth" to depth)) {
            val file = File(context.filesDir, "demo-$key-${UUID.randomUUID()}.png")
            file.outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
            prefs(context).edit().putString(key, file.path).apply()
            bitmap.recycle()
        }
        prefs(context).edit().remove("mask").remove("original").apply()
    }
}
